// Builds both versions of the web test from web/src (no dependencies):
//   web/dist/site/      full page + manifest + service worker (home-screen/offline build)
//   web/dist/artifact.html  single fragment for a Claude artifact preview
// Usage: node web/build.mjs
import { readFileSync, writeFileSync, mkdirSync, copyFileSync, readdirSync, rmSync } from "node:fs";
import { createHash } from "node:crypto";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(fileURLToPath(import.meta.url));
const read = (p) => readFileSync(join(root, p), "utf8");
// Bundled UI font (Barlow Semi Condensed, SIL OFL; see src/fonts), inlined so it works offline.
const fontFaces = [500, 600, 700, 800].map((w) => `@font-face { font-family: "Pocket Sans"; font-style: normal; font-weight: ${w}; font-display: swap; src: url(data:font/woff2;base64,${readFileSync(join(root, "src/fonts", `barlow-semi-condensed-latin-${w}-normal.woff2`)).toString("base64")}) format("woff2"); }`).join("\n");
const css = fontFaces + "\n" + read("src/styles.css");
const body = read("src/body.html");
const timing = read("src/timing.js");
const nosleep = read("src/vendor/nosleep-media.js");
const sounds = read("src/sounds.js");
// Recorded kits: processed WAVs from web/samples, inlined as base64 so the page
// works offline and inside an artifact.
const kitsIndex = JSON.parse(read("samples/kits.json"));
const sampleKits = kitsIndex.kits.map((k) => ({
  id: k.id, label: k.label, note: k.note,
  levels: Object.fromEntries(Object.entries(k.levels).map(([lv, takes]) => [lv, takes.map((t) => readFileSync(join(root, "samples", t.file)).toString("base64"))])),
}));
const drumsIndex = JSON.parse(read("samples/drums.json"));
const drumVoices = drumsIndex.voices.map((v) => ({
  id: v.id, label: v.label,
  levels: Object.fromEntries(Object.entries(v.levels).map(([lv, takes]) => [lv, takes.map((t) => readFileSync(join(root, "samples", t.file)).toString("base64"))])),
}));
const samplesScript = `/* ${kitsIndex.source} */\nwindow.POCKET_SAMPLE_KITS = ${JSON.stringify(sampleKits)};\nwindow.POCKET_DRUM_VOICES = ${JSON.stringify(drumVoices)};`;
const app = read("src/app.js");
// PDF charts: pdf.js (Apache-2.0, src/vendor/pdfjs), kept as inert text and only
// run when a chart is first shown, so it costs nothing at start-up.
const pdfBlocks = `<script type="text/plain" id="pdfjs-src">${read("src/vendor/pdfjs/pdf.min.js")}</script>
<script type="text/plain" id="pdfjs-worker-src">${read("src/vendor/pdfjs/pdf.worker.min.js")}</script>`;
const TITLE = "POCKET Web Test";

const dist = join(root, "dist");
rmSync(dist, { recursive: true, force: true });
mkdirSync(join(dist, "site"), { recursive: true });

// Artifact: the host adds doctype/head; title + style go at the top.
writeFileSync(join(dist, "artifact.html"), `<title>${TITLE}</title>
<meta name="claude:viewport-fit-sides" content="cover">
<style>
${css}
</style>
${body}
<script>
${nosleep}
</script>
<script>
${timing}
</script>
<script>
${sounds}
</script>
<script>
${samplesScript}
</script>
${pdfBlocks}
<script>
${app}
</script>
`);

// Home-screen build.
const index = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
<title>${TITLE}</title>
<meta name="theme-color" content="#14171b">
<meta name="apple-mobile-web-app-capable" content="yes">
<meta name="mobile-web-app-capable" content="yes">
<meta name="apple-mobile-web-app-title" content="POCKET">
<meta name="apple-mobile-web-app-status-bar-style" content="black-translucent">
<link rel="manifest" href="manifest.webmanifest">
<link rel="apple-touch-icon" href="apple-touch-icon.png">
<style>
:root { padding-top: env(safe-area-inset-top, 0px); padding-bottom: env(safe-area-inset-bottom, 0px); }
body { margin: 0; }
[hidden] { display: none !important; }
${css}
</style>
</head>
<body>
${body}
<script>window.POCKET_PWA = true;</script>
<script>
${nosleep}
</script>
<script>
${timing}
</script>
<script>
${sounds}
</script>
<script>
${samplesScript}
</script>
${pdfBlocks}
<script>
${app}
</script>
</body>
</html>
`;
writeFileSync(join(dist, "site", "index.html"), index);
const pub = readdirSync(join(root, "public"));
for (const f of pub) copyFileSync(join(root, "public", f), join(dist, "site", f));

const version = createHash("sha256").update(index).update(pub.join()).digest("hex").slice(0, 12);
const assets = ["./", "index.html", ...pub];
writeFileSync(join(dist, "site", "sw.js"), `// Generated by web/build.mjs — cache-first offline copy.
const CACHE = "pocket-${version}";
const ASSETS = ${JSON.stringify(assets)};
self.addEventListener("install", (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(ASSETS)).then(() => self.skipWaiting()));
});
self.addEventListener("activate", (e) => {
  e.waitUntil(caches.keys()
    .then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k))))
    .then(() => self.clients.claim()));
});
self.addEventListener("fetch", (e) => {
  if (e.request.method !== "GET") return;
  e.respondWith(caches.match(e.request, { ignoreSearch: true }).then((hit) => hit || fetch(e.request)));
});
`);
console.log(`built web/dist (version ${version})`);
